/**
 * "ירושלים - שוק מחנה יהודה" → "שוק מחנה יהודה, ירושלים"; quotes dropped.
 * Returns undefined when the official wording is already short enough.
 */
export function shortPlace(place) {
  if (!place) return undefined;
  if (SHORT[place]) return SHORT[place];
  const m = place.match(/^([^-–,]+?)\s+[-–]\s+(.+)$/);
  const out = (m ? `${m[2]}, ${m[1]}` : place).replace(/"/g, '').trim();
  return out === place ? undefined : out;
}
